import { test, expect, type APIRequestContext } from "@playwright/test";
const api = "http://127.0.0.1:18000/api";
const base = "http://127.0.0.1:15173";
async function post(request: APIRequestContext, path: string, data: unknown) {
  const response = await request.post(api + path, { data }); expect(response.ok()).toBe(true); return response.json();
}

test("customer searches full descriptions, combines filters and searches archives separately", async ({ browser, request }, info) => {
  const one = await post(request, "/projects", { name: `Search checkout ${info.project.name}` });
  const two = await post(request, "/projects", { name: `Search billing ${info.project.name}` });
  const links = await Promise.all([post(request, `/projects/${one.id}/intake-link`, {}), post(request, `/projects/${two.id}/intake-link`, {})]);
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  await context.addCookies([{ name: "bugbrief_customer", value: Buffer.alloc(32, info.project.name === "desktop" ? "r" : "s").toString("base64url"), url: base }]);
  async function report(project: number, text: string, send = true) {
    const draft = await post(context.request, `/public/intake/${links[project].token}/submissions`, { client_nonce: crypto.randomUUID(), text });
    if (send) await post(context.request, `/public/submissions/${draft.access_token}/submit`, { draft_version: draft.draft_version });
    return draft;
  }
  const first = await report(0, "Checkout stopped. " + "x".repeat(180) + " SECRET-TAIL हिंदी");
  const retest = await report(1, "A billing issue to retest");
  const archived = await report(0, "Archived SECRET-TAIL report");
  await report(1, "A report still being drafted", false);
  const feedback = await (await request.get(api + "/feedback")).json();
  const firstRow = feedback.find((row: { id: string }) => row.id.slice(0, 8).toUpperCase() === first.reference);
  const retestRow = feedback.find((row: { id: string }) => row.id.slice(0, 8).toUpperCase() === retest.reference);
  expect((await request.patch(`${api}/feedback/${firstRow.id}/workflow`, { data: { version: 0, status: "needs_information", assigned_employee_id: null, note: "Please provide more details." } })).ok()).toBe(true);
  await post(request, `/projects/${two.id}/members/employee`, { email: "workflow-employee@example.com" });
  const employee = (await (await request.get(api + "/employees")).json()).find((person: { name: string }) => person.name === "Workflow Employee");
  let state = await (await request.patch(`${api}/feedback/${retestRow.id}/workflow`, { data: { version: 0, status: "in_progress", assigned_employee_id: employee.id, note: "Investigating." } })).json();
  expect((await request.patch(`${api}/feedback/${retestRow.id}/workflow`, { data: { version: state.version, status: "ready_to_retest", fix_details: { summary: "Checkout corrected.", location: "Test website, current version.", steps: "Open checkout and press Pay now." }, assigned_employee_id: employee.id, note: "Try again." } })).ok()).toBe(true);
  expect((await context.request.patch(`${api}/public/submissions/${archived.access_token}/archive`, { data: { archived: true } })).ok()).toBe(true);
  const page = await context.newPage(); await page.goto(base + "/customer");
  const search = page.getByRole("region", { name: "Find your reports", exact: true });
  const list = page.locator(".customer-report-list");
  await expect(list.locator("article")).toHaveCount(3);
  await search.getByLabel("Search your reports", { exact: true }).fill("secret-tail");
  await expect(list.locator("article")).toHaveCount(1);
  await expect(list).toContainText("BB-" + first.reference);
  await search.getByLabel("Filter your reports by project", { exact: true }).selectOption(two.id);
  await expect(page.getByRole("heading", { name: "No reports match these filters." })).toBeVisible();
  await search.getByRole("button", { name: "Reset report filters" }).click();
  await search.getByLabel("Filter your reports by action needed", { exact: true }).selectOption("retest");
  await expect(list.locator("article")).toHaveCount(1);
  await expect(list).toContainText("BB-" + retest.reference);
  await search.getByLabel("Filter your reports by status", { exact: true }).selectOption("needs_information");
  await expect(page.getByRole("heading", { name: "No reports match these filters." })).toBeVisible();
  await search.getByRole("button", { name: "Reset report filters" }).click();
  await search.getByLabel("Search your reports", { exact: true }).fill("BB-" + first.reference);
  await expect(list.locator("article")).toHaveCount(1);
  await page.getByRole("button", { name: "Archived reports", exact: true }).click();
  await expect(page.getByRole("heading", { name: "No reports match these filters." })).toBeVisible();
  await search.getByLabel("Search your reports", { exact: true }).fill("secret-tail");
  await expect(list.locator("article")).toHaveCount(1);
  await expect(list).toContainText("BB-" + archived.reference);
  await search.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `../test-results/${info.project.name}-customer-search.png`, fullPage: false });
  await page.getByRole("button", { name: "Active reports", exact: true }).click();
  await expect(list).toContainText("BB-" + first.reference);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});

test("older activity retains actor names, isolates private changes and works for project viewers", async ({ browser, request, page }, info) => {
  const token = Buffer.alloc(32, info.project.name === "desktop" ? "l" : "m").toString("base64url");
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const customer = await context.newPage(); await customer.goto(`${base}/s/${token}`);
  const history = customer.getByRole("region", { name: "Progress history", exact: true });
  await expect(history.locator("li")).toHaveCount(50);
  await history.getByRole("button", { name: "Load older updates", exact: true }).click();
  await expect(history.locator("li")).toHaveCount(100);
  await history.getByRole("button", { name: "Load older updates", exact: true }).click();
  await expect(history.locator("li")).toHaveCount(130);
  await expect(history).not.toContainText("Private activity");
  await expect(history).toContainText("Actor not recorded");
  await expect(history).toContainText("By Fixture employee");
  await customer.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(history.locator("li")).toHaveCount(130);
  const reports = await (await request.get(api + "/feedback?include_archived=true")).json();
  const record = reports.find((row: { text: string }) => row.text === `Archived history fixture ${info.project.name}`);
  const projects = await (await request.get(api + "/projects")).json();
  const project = projects.find((row: { id: string }) => row.id === record.project_id);
  const email = `experience-${info.project.name}@example.test`;
  await post(request, `/projects/${project.id}/members/employee`, { email });
  const employee = (await (await request.get(api + "/employees")).json()).find((row: { name: string }) => row.name === `Personal ${info.project.name}`);
  expect((await request.patch(`${api}/projects/${project.id}/members/employee/${employee.id}`, { data: { role: "viewer", can_delete: false } })).ok()).toBe(true);
  const employeeContext = await browser.newContext({ extraHTTPHeaders: {} });
  await employeeContext.addCookies([{ name: "bugbrief_employee", value: Buffer.alloc(32, info.project.name === "desktop" ? "f" : "g").toString("base64url"), url: base }]);
  const work = await employeeContext.newPage(); await work.goto(`${base}/workspace?report=${record.id}`);
  const team = work.getByRole("region", { name: "Progress history", exact: true });
  await expect(team.locator("li")).toHaveCount(50);
  await team.getByRole("button", { name: "Load older updates", exact: true }).click();
  await team.getByRole("button", { name: "Load older updates", exact: true }).click();
  await expect(team.locator("li")).toHaveCount(135);
  await expect(team).toContainText("Private activity");
  await expect(team).not.toContainText("Customer-only activity");
  await expect(work.getByRole("button", { name: "Restore report", exact: true })).toBeDisabled();
  expect((await employeeContext.request.get(`${api}/projects/${project.id}/activity`)).status()).toBe(403);
  await page.goto("/workspace/team");
  const access = page.getByRole("region", { name: "Project access", exact: true });
  await access.getByLabel("Manage project", { exact: true }).selectOption(project.id);
  await access.getByText("Project activity history", { exact: true }).click();
  const projectHistory = access.getByRole("region", { name: "Project activity", exact: true });
  await expect(projectHistory).toContainText("Employee permissions changed");
  await expect(projectHistory).toContainText("By Workspace owner");
  await history.scrollIntoViewIfNeeded();
  await customer.screenshot({ path: `../test-results/${info.project.name}-activity-history.png`, fullPage: false });
  expect(await customer.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await employeeContext.close(); await context.close();
});
