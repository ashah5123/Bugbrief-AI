import { test, expect } from "@playwright/test";
const base = "http://127.0.0.1:15173";
const api = "http://127.0.0.1:18000/api";

test("stale draft answers survive a conflict, reload and explicit recovery", async ({ browser, request }, info) => {
  const project = await (await request.post(`${api}/projects`, { data: { name: `Draft conflict ${info.project.name}` } })).json();
  const link = await (await request.post(`${api}/projects/${project.id}/intake-link`, { data: {} })).json();
  const draft = await (await request.post(`${api}/public/intake/${link.token}/submissions`, { data: { client_nonce: crypto.randomUUID(), text: "Original symptom", guided_details: { expected: "Original expectation" } } })).json();
  const contexts = await Promise.all([browser.newContext({ extraHTTPHeaders: {} }), browser.newContext({ extraHTTPHeaders: {} })]);
  const first = await contexts[0].newPage(); const second = await contexts[1].newPage();
  for (const tab of [first, second]) await tab.goto(`${base}/s/${draft.access_token}`);
  await first.getByLabel("What did you expect to happen?", { exact: true }).fill("Newer saved answer");
  await first.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(first.getByRole("heading", { name: "Ready for the team?" })).toBeVisible();
  await second.getByLabel("What did you expect to happen?", { exact: true }).fill("My unsaved answer");
  await second.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(second.getByRole("heading", { name: "This draft changed in another tab." })).toBeVisible();
  await expect(second.getByLabel("What did you expect to happen?", { exact: true })).toHaveValue("My unsaved answer");
  await second.reload();
  await second.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(second.getByRole("heading", { name: "This draft changed in another tab." })).toBeVisible();
  await second.getByRole("button", { name: "Load latest draft", exact: true }).click();
  await expect(second.getByLabel("What did you expect to happen?", { exact: true })).toHaveValue("Newer saved answer");
  await second.reload();
  await second.getByText("Your unsaved copy", { exact: true }).click();
  await expect(second.locator(".draft-conflict")).toContainText("My unsaved answer");
  await second.getByRole("button", { name: "Use my copy for editing" }).click();
  await second.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(second.getByRole("region", { name: "Customer's bug details" })).toContainText("My unsaved answer");
  await first.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(first.getByRole("heading", { name: "This draft changed in another tab." })).toBeVisible();
  expect((await (await request.get(`${api}/public/submissions/${draft.access_token}`)).json()).stage).toBe("draft");
  await second.route("**/api/public/submissions/*/submit", async route => { await route.fetch(); await route.abort("failed"); }, { times: 1 });
  await second.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(second.getByRole("alert")).toBeVisible();
  await second.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(second.getByRole("heading", { name: "The team has your feedback." })).toBeVisible();
  for (const context of contexts) await context.close();
});

test("older replies load without exposing private notes or disappearing on refresh", async ({ browser, request, page }, info) => {
  const token = Buffer.alloc(32, info.project.name === "desktop" ? "l" : "m").toString("base64url");
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const customer = await context.newPage();
  await customer.goto(`${base}/s/${token}`);
  const conversation = customer.getByRole("region", { name: "Report conversation" });
  await expect(conversation.locator(".report-message")).toHaveCount(100);
  await conversation.getByRole("button", { name: "Load older replies" }).click();
  await expect(conversation.locator(".report-message")).toHaveCount(200);
  await conversation.getByRole("button", { name: "Load older replies" }).click();
  await expect(conversation.locator(".report-message")).toHaveCount(205);
  await expect(conversation.getByRole("button", { name: "Load older replies" })).toHaveCount(0);
  await expect(conversation).not.toContainText("Private history");
  await conversation.getByLabel("Your reply", { exact: true }).fill("A new reply after loading history");
  await conversation.getByRole("button", { name: "Send reply", exact: true }).click();
  await expect(conversation.locator(".report-message")).toHaveCount(206);
  await customer.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(conversation.locator(".report-message")).toHaveCount(206);
  const reports = await (await request.get(`${api}/feedback?include_archived=true`)).json();
  const item = reports.find((value: { text: string }) => value.text === `Archived history fixture ${info.project.name}`);
  await page.goto(`/workspace?report=${item.id}`);
  const team = page.getByRole("region", { name: "Report conversation" });
  await expect(team.locator(".report-message")).toHaveCount(100);
  await team.getByRole("button", { name: "Load older replies" }).click();
  await team.getByRole("button", { name: "Load older replies" }).click();
  await expect(team.locator(".report-message")).toHaveCount(216);
  await expect(team.locator(".internal-message")).toHaveCount(10);
  await context.close();
});

test("owner sets employee roles; archive and restore remain independent from customer lists", async ({ browser, request, page }, info) => {
  const project = await (await request.post(`${api}/projects`, { data: { name: `Permissions archive ${info.project.name}` } })).json();
  const email = `experience-${info.project.name}@example.test`;
  await request.post(`${api}/projects/${project.id}/members/employee`, { data: { email } });
  const employees = await (await request.get(`${api}/employees`)).json();
  const employee = employees.find((value: { name: string }) => value.name === `Personal ${info.project.name}`);
  const rolePath = `${api}/projects/${project.id}/members/employee/${employee.id}`;
  await request.patch(rolePath, { data: { role: "viewer", can_delete: false } });
  const customer = await browser.newContext({ extraHTTPHeaders: {} });
  await customer.addCookies([{ name: "bugbrief_customer", value: Buffer.alloc(32, info.project.name === "desktop" ? "j" : "k").toString("base64url"), url: base }]);
  const link = await (await request.post(`${api}/projects/${project.id}/intake-link`, { data: {} })).json();
  const draft = await (await customer.request.post(`${api}/public/intake/${link.token}/submissions`, { data: { client_nonce: crypto.randomUUID(), text: "Report for archive checks" } })).json();
  await customer.request.post(`${api}/public/submissions/${draft.access_token}/submit`, { data: {} });
  const record = (await (await request.get(`${api}/feedback`)).json()).find((value: { project_id: string }) => value.project_id === project.id);
  const employeeContext = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  await employeeContext.addCookies([{ name: "bugbrief_employee", value: Buffer.alloc(32, info.project.name === "desktop" ? "f" : "g").toString("base64url"), url: base }]);
  const work = await employeeContext.newPage();
  await work.goto(`${base}/workspace?report=${record.id}`);
  await expect(work.getByText("You have view-only access.", { exact: false })).toBeVisible();
  await expect(work.getByRole("button", { name: "Archive report", exact: true })).toBeDisabled();
  await expect(work.getByRole("button", { name: "Delete report", exact: true })).toBeDisabled();
  expect((await employeeContext.request.post(`${api}/feedback/${record.id}/messages`, { data: { body: "Blocked direct write" } })).status()).toBe(403);
  await page.goto("/workspace/team");
  const access = page.getByRole("region", { name: "Project access", exact: true });
  await access.getByLabel("Manage project", { exact: true }).selectOption(project.id);
  await access.getByLabel(`Project role for Personal ${info.project.name}`, { exact: true }).selectOption("contributor");
  await work.reload();
  await expect(work.getByRole("button", { name: "Archive report", exact: true })).toBeEnabled();
  await expect(work.getByRole("button", { name: "Delete report", exact: true })).toBeDisabled();
  await work.getByRole("button", { name: "Archive report", exact: true }).click();
  await work.getByRole("button", { name: "Archived reports", exact: true }).click();
  await expect(work.locator(".feedback-row").filter({ hasText: "Report for archive checks" })).toBeVisible();
  const portal = await customer.newPage();
  await portal.goto(`${base}/customer`);
  await expect(portal.locator(".customer-report-list article").filter({ hasText: "Report for archive checks" })).toBeVisible();
  await portal.locator(".customer-report-list article").filter({ hasText: "Report for archive checks" }).getByRole("button", { name: "Archive report", exact: true }).click();
  await portal.getByRole("button", { name: "Archived reports", exact: true }).click();
  const archived = portal.locator(".customer-report-list article").filter({ hasText: "Report for archive checks" });
  await expect(archived).toBeVisible();
  await archived.getByRole("button", { name: "Restore report", exact: true }).click();
  await portal.getByRole("button", { name: "Active reports", exact: true }).click();
  await expect(portal.locator(".customer-report-list article").filter({ hasText: "Report for archive checks" })).toBeVisible();
  await work.getByRole("button", { name: "Restore report", exact: true }).click();
  await work.getByRole("button", { name: "Active reports", exact: true }).click();
  await expect(work.locator(".feedback-row").filter({ hasText: "Report for archive checks" })).toBeVisible();
  await access.getByLabel(`Project role for Personal ${info.project.name}`, { exact: true }).selectOption("manager");
  await expect(access.getByLabel(`Allow permanent deletion for Personal ${info.project.name}`, { exact: true })).not.toBeChecked();
  await access.getByLabel(`Allow permanent deletion for Personal ${info.project.name}`, { exact: true }).check();
  await expect(access.getByLabel(`Allow permanent deletion for Personal ${info.project.name}`, { exact: true })).toBeEnabled();
  await work.reload();
  await expect(work.getByRole("button", { name: "Delete report", exact: true })).toBeEnabled();
  await access.screenshot({ path: `../test-results/${info.project.name}-employee-permissions.png` });
  for (const target of [work, portal]) expect(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await employeeContext.close(); await customer.close();
});

test("guest archives and restores a report from the saved browser list", async ({ browser, request }, info) => {
  const project = await (await request.post(`${api}/projects`, { data: { name: `Guest archive ${info.project.name}` } })).json();
  const link = await (await request.post(`${api}/projects/${project.id}/intake-link`, { data: {} })).json();
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const page = await context.newPage();
  await page.goto(`${base}/c/${link.token}`);
  await page.getByLabel("What went wrong?", { exact: true }).fill("My guest report for archiving");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(page.getByRole("heading", { name: "The team has your feedback." })).toBeVisible();
  await page.getByRole("button", { name: "Archive report", exact: true }).click();
  await expect(page.getByRole("button", { name: "Restore report", exact: true })).toBeVisible();
  await page.goto(`${base}/customer`);
  await expect(page.locator(".customer-report-list article")).toHaveCount(0);
  await page.getByRole("button", { name: "Archived reports", exact: true }).click();
  await expect(page.locator(".customer-report-list article")).toHaveCount(1);
  await page.getByRole("button", { name: "Restore report", exact: true }).click();
  await page.getByRole("button", { name: "Active reports", exact: true }).click();
  await expect(page.locator(".customer-report-list article")).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});
