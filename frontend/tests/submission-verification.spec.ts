import { test, expect } from "@playwright/test";
const base = "http://127.0.0.1:15173";
const api = "http://127.0.0.1:18000/api";

test("a change after review blocks final send; reviewing again and retrying a lost response sends once", async ({ browser, request }, info) => {
  const project = await (await request.post(`${api}/projects`, { data: { name: `Final send race ${info.project.name}` } })).json();
  const link = await (await request.post(`${api}/projects/${project.id}/intake-link`, { data: {} })).json();
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const page = await context.newPage();
  await page.goto(`${base}/c/${link.token}`);
  await page.getByLabel("What went wrong?", { exact: true }).fill("The original reviewed symptom");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Ready for the team?" })).toBeVisible();
  const token = new URL(page.url()).pathname.split("/")[2];
  const path = `${api}/public/submissions/${token}`;
  await page.route("**/api/public/submissions/*/submit", async route => {
    const payload = route.request().postDataJSON();
    expect(payload.draft_version).toBeGreaterThan(0);
    const edited = await context.request.put(path, { data: { text: "New symptom from another tab after review", guided_details: { expected: "A newer expected result" }, draft_version: payload.draft_version } });
    expect(edited.ok()).toBe(true);
    await route.continue();
  }, { times: 1 });
  await page.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(page.getByRole("heading", { name: "This draft changed in another tab." })).toBeVisible();
  expect((await (await context.request.get(path)).json()).stage).toBe("draft");
  const inbox = await (await request.get(`${api}/feedback`)).json();
  expect(inbox.filter((entry: { project_id: string }) => entry.project_id === project.id)).toHaveLength(0);
  await page.getByRole("button", { name: "Load latest draft", exact: true }).click();
  await expect(page.getByLabel("What went wrong?", { exact: true })).toHaveValue("New symptom from another tab after review");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("region", { name: "Customer's bug details" })).toContainText("A newer expected result");
  await page.route("**/api/public/submissions/*/submit", async route => { await route.fetch(); await route.abort("failed"); }, { times: 1 });
  await page.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await page.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(page.getByRole("heading", { name: "The team has your feedback." })).toBeVisible();
  const final = (await (await request.get(`${api}/feedback`)).json()).filter((entry: { project_id: string }) => entry.project_id === project.id);
  expect(final).toHaveLength(1);
  expect(final[0].text).toBe("New symptom from another tab after review");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});

test("private invitation stays pending until the customer completes email verification", async ({ browser, request, page }, info) => {
  const name = `Private finance portal ${info.project.name}`;
  const email = `pending-${info.project.name}@example.test`;
  const project = await (await request.post(`${api}/projects`, { data: { name, team_name: "Private team" } })).json();
  const link = await (await request.post(`${api}/projects/${project.id}/intake-link`, { data: {} })).json();
  await request.patch(`${api}/projects/${project.id}/access`, { data: { mode: "members" } });
  const grant = await request.post(`${api}/projects/${project.id}/members/customer`, { data: { email } });
  expect(grant.ok()).toBe(true);
  const context = await browser.newContext({ extraHTTPHeaders: {}, viewport: info.project.name === "mobile" ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  await context.addCookies([{ name: "bugbrief_customer", value: Buffer.alloc(32, info.project.name === "desktop" ? "p" : "q").toString("base64url"), url: base }]);
  const portal = await context.newPage();
  await portal.goto(`${base}/customer`);
  await expect(portal.getByRole("heading", { name: "Verify your email to open your private projects." })).toBeVisible();
  await expect(portal.locator(".customer-project-grid")).toContainText("Private project invitation");
  await expect(portal.locator(".customer-project-grid")).not.toContainText(name);
  await expect(portal.getByRole("link", { name: "Report an issue", exact: true })).toHaveCount(0);
  const form = await context.newPage();
  await form.goto(`${base}/c/${link.token}`);
  await expect(form.getByRole("heading", { name: "Verify your email to open this project." })).toBeVisible();
  await form.getByRole("button", { name: "Resend verification", exact: true }).click();
  await expect(form.getByRole("status")).toContainText("Verification requested");
  expect((await context.request.get(`${api}/public/intake/${link.token}`)).status()).toBe(403);
  await page.goto("/workspace/team");
  const access = page.getByRole("region", { name: "Project access", exact: true });
  await access.getByLabel("Manage project", { exact: true }).selectOption(project.id);
  const member = access.locator(".team-member").filter({ hasText: email });
  await expect(member).toContainText("Pending · customer must verify");
  await access.screenshot({ path: `../test-results/${info.project.name}-pending-private-access.png` });
  const outbox = await (await request.get(`${api}/team/outbox`)).json();
  const mail = outbox.find((entry: { recipient: string; body: string }) => entry.recipient === email && entry.body.includes("/verify/"));
  const token = mail.body.match(/\/verify\/([A-Za-z0-9_-]{43})/)[1];
  const verification = await context.newPage();
  await verification.goto(`${base}/account#customer/verify/${token}`);
  await verification.getByRole("button", { name: "Verify email", exact: true }).click();
  await expect(verification.getByRole("status")).toContainText("Email verified");
  await portal.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(portal.getByText("✓ Email verified", { exact: true })).toBeVisible();
  await expect(portal.getByRole("heading", { name, exact: true })).toBeVisible();
  await expect(portal.locator(".customer-project-grid").getByRole("link", { name: "Report an issue", exact: true })).toBeVisible();
  await form.reload();
  await form.getByLabel("What went wrong?", { exact: true }).fill("Verified customer's private report");
  await form.getByRole("button", { name: "Continue", exact: true }).click();
  await form.getByRole("button", { name: "Send to the agency", exact: true }).click();
  await expect(form.getByRole("heading", { name: "The team has your feedback." })).toBeVisible();
  await page.reload();
  await access.getByLabel("Manage project", { exact: true }).selectOption(project.id);
  await expect(member).toContainText("Email verified · access active");
  for (const target of [form, portal, page]) expect(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});
